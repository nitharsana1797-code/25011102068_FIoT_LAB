#include "main.h"

UART_HandleTypeDef huart2;
void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_USART2_UART_Init(void);

int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_USART2_UART_Init();

  uint8_t transmitChar = 'A';
  uint8_t receivedChar;
  uint32_t lastTransmitTime = HAL_GetTick();

  uint8_t welcome[] = "\r\nTask 9A: UART Transmit and Receive Echo\r\n";
  HAL_UART_Transmit(&huart2, welcome, sizeof(welcome) - 1, HAL_MAX_DELAY);

  while (1)
  {
    /* Transmit one character repeatedly, once every second. */
    if ((HAL_GetTick() - lastTransmitTime) >= 1000U)
    {
      HAL_UART_Transmit(&huart2, &transmitChar, 1, HAL_MAX_DELAY);
      HAL_UART_Transmit(&huart2, (uint8_t *)"\r\n", 2, HAL_MAX_DELAY);
      lastTransmitTime = HAL_GetTick();
    }

    /* Echo every character received from the PC terminal. */
    if (HAL_UART_Receive(&huart2, &receivedChar, 1, 10) == HAL_OK)
    {
      HAL_UART_Transmit(&huart2, &receivedChar, 1, HAL_MAX_DELAY);
      if (receivedChar == '\r')
      {
        uint8_t newline = '\n';
        HAL_UART_Transmit(&huart2, &newline, 1, HAL_MAX_DELAY);
      }
    }
  }
}


